#!/usr/bin/env python3
"""Build the committed, self-contained KASPberry smoke-test fixture.

The source material lives under ``dev/smoke_test_builder/source`` and the
runtime fixture is written to ``.test`` by default.

The builder creates only files that KASPberry needs at runtime:

    .test/
    ├── config.yaml
    ├── genotypes.tsv
    ├── chromosomes.tsv
    ├── annotations.tsv
    ├── regions/
    ├── genomes/
    ├── annotations/
    └── resources/

``.test/results`` is deliberately left untouched. It is produced by KASPberry
and should be ignored by Git.

Regional block FASTAs
---------------------
Each FASTA in ``<source-dir>/blocks`` must contain one target record for every
genotype: Karur, Soldur, Belalur, Lloyd and Dic2.

A block may additionally contain an explicit homoeologue record named
``<genotype>_B``. If a ``*_B`` record is absent, a same-length synthetic
homoeologue is generated by deterministic substitutions. Blocks are
concatenated in lexicographic filename order and are the ONLY sequences used
to build the regional FASTAs analysed by SibeliaZ/SeqTUI.

Optional whole-genome-only extra sequences
------------------------------------------
If ``<source-dir>/genome_extras`` exists, FASTA files in that directory are
added only to the generated whole-genome FASTA files and chromosomes.tsv.
They never enter the regional FASTAs.

Extra FASTA filenames encode PolyMarker chromosome metadata as:

    <homoeologous_group><subgenome>__<label>.fasta

For example:

    5A__snp450_duplicate.fasta

Static runtime inputs
---------------------
The following source files are copied into the generated fixture:

- ``<source-dir>/gffs/*`` -> ``.test/annotations/*``
- ``<source-dir>/annotations.tsv`` -> ``.test/annotations.tsv`` with rewritten
  fixture-relative GFF paths
- ``<source-dir>/resources/mini_TE_lib.fasta`` ->
  ``.test/resources/mini_TE_lib.fasta``

The builder writes fixture-relative paths in all generated tables so the
fixture can be executed with ``--directory .test`` from any current working
directory.
"""

from __future__ import annotations

import argparse
import csv
import random
import re
import shutil
from dataclasses import dataclass, field
from pathlib import Path

DNA = "ACGT"
FASTA_EXTENSIONS = {".fa", ".fasta", ".fna"}
FASTA_LINE_WIDTH = 80

GENOTYPES = ["Karur", "Soldur", "Belalur", "Lloyd", "Dic2"]
GROUP_BY_GENOTYPE = {"Karur": "A", "Soldur": "B"}
FASTA_HEADER_ALIASES = {"Dic2": "Dic2_mlk"}

HOMOEOLOGOUS_GROUP = "7"
TARGET_SUBGENOME = "A"
HOMOEOLOGUE_SUBGENOME = "B"
INPUT_HOMOEOLOGUE_SUFFIX = "_B"
OUTPUT_HOMOEOLOGUE_SUFFIX = "_B"

AUTO_HOMOEOLOGUE_INTERVAL = 50
AUTO_HOMOEOLOGUE_OFFSET = 25

EXTRA_FILENAME_PATTERN = re.compile(
    r"^(?P<group>.+)(?P<subgenome>[A-Za-z0-9])__(?P<label>[A-Za-z0-9_.-]+)$"
)

REPO_ROOT = Path(__file__).resolve().parents[3]
DEFAULT_SOURCE_DIR = REPO_ROOT / "dev" / "smoke_test_builder" / "source"
DEFAULT_OUTPUT_DIR = REPO_ROOT / ".test"


@dataclass(frozen=True)
class Segment:
    kind: str
    name: str
    sequence: str

    @property
    def length(self) -> int:
        return len(self.sequence)


@dataclass(frozen=True)
class Assembly:
    sequence: str
    segments: list[Segment]


@dataclass(frozen=True)
class GenomeExtra:
    label: str
    homoeologous_group: str
    subgenome: str
    sequence: str


@dataclass(frozen=True)
class DatasetRecord:
    genotype: str
    target_region: Assembly
    homoeologue_region: Assembly
    target_genome: Assembly
    homoeologue_genome: Assembly
    region_start_1based: int
    genome_extras: tuple[GenomeExtra, ...] = field(default_factory=tuple)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Build the self-contained KASPberry smoke-test fixture from its "
            "versioned source material."
        )
    )
    parser.add_argument(
        "--source-dir",
        type=Path,
        default=DEFAULT_SOURCE_DIR,
        help=(
            "Smoke-test source directory. Default: "
            f"{DEFAULT_SOURCE_DIR.relative_to(REPO_ROOT)}"
        ),
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help=(
            "Generated runtime fixture directory. Default: "
            f"{DEFAULT_OUTPUT_DIR.relative_to(REPO_ROOT)}"
        ),
    )
    parser.add_argument(
        "--spacer-length",
        type=int,
        default=250,
        help="Length of genotype-specific spacers between blocks. Default: 250.",
    )
    parser.add_argument(
        "--flank-length",
        type=int,
        default=800,
        help="Base whole-genome flank length on each side. Default: 800.",
    )
    parser.add_argument(
        "--flank-jitter",
        type=int,
        default=100,
        help="Maximum trimming of shared whole-genome flanks. Default: 100.",
    )
    parser.add_argument("--seed", type=int, default=0)
    return parser.parse_args()


def normalize_sequence(sequence: str) -> str:
    sequence = re.sub(r"\s+", "", sequence).upper()
    invalid = set(sequence) - set(DNA)
    if not sequence or invalid:
        raise ValueError(
            "Sequences must contain only A/C/G/T; invalid symbols: "
            + ", ".join(sorted(invalid))
        )
    return sequence


def read_fasta(path: Path) -> dict[str, str]:
    records: dict[str, list[str]] = {}
    current: str | None = None

    with path.open(encoding="utf-8") as handle:
        for raw_line in handle:
            line = raw_line.strip()
            if not line:
                continue
            if line.startswith(">"):
                current = line[1:].split()[0]
                if current in records:
                    raise ValueError(f"{path}: duplicate FASTA record {current}")
                records[current] = []
            else:
                if current is None:
                    raise ValueError(f"{path}: sequence before first FASTA header")
                records[current].append(line)

    return {
        name: normalize_sequence("".join(parts))
        for name, parts in records.items()
    }


def wrap(sequence: str) -> str:
    return "\n".join(
        sequence[i : i + FASTA_LINE_WIDTH]
        for i in range(0, len(sequence), FASTA_LINE_WIDTH)
    )


def write_fasta(path: Path, records: list[tuple[str, str]]) -> None:
    with path.open("w", encoding="utf-8") as handle:
        for name, sequence in records:
            handle.write(f">{name}\n{wrap(sequence)}\n")


def target_record_name(genotype: str) -> str:
    return FASTA_HEADER_ALIASES.get(genotype, genotype)


def homoeologue_record_name(genotype: str) -> str:
    return f"{target_record_name(genotype)}{OUTPUT_HOMOEOLOGUE_SUFFIX}"


def safe_extra_label(label: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", label)


def extra_record_name(genotype: str, extra: GenomeExtra, index: int) -> str:
    return (
        f"{target_record_name(genotype)}_extra_"
        f"{extra.homoeologous_group}{extra.subgenome}_"
        f"{index:02d}_{safe_extra_label(extra.label)}"
    )


def mutate_homoeologue(sequence: str) -> str:
    substitutions = {"A": "C", "C": "G", "G": "T", "T": "A"}
    bases = list(sequence)
    start = AUTO_HOMOEOLOGUE_OFFSET - 1
    for index in range(start, len(bases), AUTO_HOMOEOLOGUE_INTERVAL):
        bases[index] = substitutions[bases[index]]
    return "".join(bases)


def random_dna(rng: random.Random, length: int) -> str:
    return "".join(rng.choices(DNA, k=length))


def load_blocks(input_dir: Path) -> list[tuple[str, dict[str, str]]]:
    if not input_dir.is_dir():
        raise ValueError(f"Invalid block input directory: {input_dir}")

    paths = sorted(
        path
        for path in input_dir.iterdir()
        if path.suffix.lower() in FASTA_EXTENSIONS
    )
    if not paths:
        raise ValueError(f"No FASTA block files found in {input_dir}")

    required = set(GENOTYPES)
    allowed = required | {
        f"{genotype}{INPUT_HOMOEOLOGUE_SUFFIX}"
        for genotype in GENOTYPES
    }

    blocks: list[tuple[str, dict[str, str]]] = []
    for path in paths:
        records = read_fasta(path)
        missing = sorted(required - records.keys())
        unexpected = sorted(records.keys() - allowed)

        if missing:
            raise ValueError(f"{path}: missing target records: {missing}")
        if unexpected:
            raise ValueError(f"{path}: unexpected records: {unexpected}")

        for genotype in GENOTYPES:
            b_name = f"{genotype}{INPUT_HOMOEOLOGUE_SUFFIX}"
            if b_name in records and len(records[b_name]) != len(records[genotype]):
                raise ValueError(
                    f"{path}: {b_name} must have the same length as {genotype}"
                )

        blocks.append((path.stem, records))

    return blocks


def parse_extra_filename(path: Path) -> tuple[str, str, str]:
    match = EXTRA_FILENAME_PATTERN.fullmatch(path.stem)
    if match is None:
        raise ValueError(
            f"Invalid genome-extra filename {path.name!r}. Expected "
            "<homoeologous_group><subgenome>__<label>.fasta, "
            "for example 5A__snp450_duplicate.fasta."
        )

    return (
        match.group("group"),
        match.group("subgenome"),
        match.group("label"),
    )


def load_genome_extras(
    extras_dir: Path | None,
) -> dict[str, list[GenomeExtra]]:
    extras_by_genotype: dict[str, list[GenomeExtra]] = {
        genotype: [] for genotype in GENOTYPES
    }

    if extras_dir is None or not extras_dir.exists():
        return extras_by_genotype
    if not extras_dir.is_dir():
        raise ValueError(f"Invalid genome extras directory: {extras_dir}")

    paths = sorted(
        path
        for path in extras_dir.iterdir()
        if path.suffix.lower() in FASTA_EXTENSIONS
    )

    for path in paths:
        group, subgenome, label = parse_extra_filename(path)
        records = read_fasta(path)
        unexpected = sorted(set(records) - set(GENOTYPES))
        if unexpected:
            raise ValueError(
                f"{path}: genome-extra FASTA records must be genotype names; "
                f"unexpected records: {unexpected}"
            )

        for genotype, sequence in records.items():
            extras_by_genotype[genotype].append(
                GenomeExtra(
                    label=label,
                    homoeologous_group=group,
                    subgenome=subgenome,
                    sequence=sequence,
                )
            )

    return extras_by_genotype


def block_homoeologue(records: dict[str, str], genotype: str) -> str:
    b_name = f"{genotype}{INPUT_HOMOEOLOGUE_SUFFIX}"
    if b_name in records:
        return records[b_name]
    return mutate_homoeologue(records[genotype])


def assemble_regions(
    blocks: list[tuple[str, dict[str, str]]],
    rng: random.Random,
    spacer_length: int,
) -> tuple[dict[str, Assembly], dict[str, Assembly]]:
    target_segments: dict[str, list[Segment]] = {
        genotype: [] for genotype in GENOTYPES
    }
    b_segments: dict[str, list[Segment]] = {
        genotype: [] for genotype in GENOTYPES
    }

    for block_index, (block_name, records) in enumerate(blocks):
        for genotype in GENOTYPES:
            target_segments[genotype].append(
                Segment("block", block_name, records[genotype])
            )
            b_segments[genotype].append(
                Segment("block", block_name, block_homoeologue(records, genotype))
            )

        if block_index == len(blocks) - 1:
            continue

        spacer_name = f"spacer_{block_index + 1}"
        for genotype in GENOTYPES:
            target_spacer = random_dna(rng, spacer_length)
            target_segments[genotype].append(
                Segment("spacer", spacer_name, target_spacer)
            )
            b_segments[genotype].append(
                Segment("spacer", spacer_name, mutate_homoeologue(target_spacer))
            )

    def to_assembly(segments: list[Segment]) -> Assembly:
        return Assembly(
            sequence="".join(segment.sequence for segment in segments),
            segments=segments,
        )

    return (
        {g: to_assembly(target_segments[g]) for g in GENOTYPES},
        {g: to_assembly(b_segments[g]) for g in GENOTYPES},
    )


def trim_left(sequence: str, rng: random.Random, jitter: int) -> str:
    return sequence[rng.randint(0, jitter) :]


def trim_right(sequence: str, rng: random.Random, jitter: int) -> str:
    trim = rng.randint(0, jitter)
    return sequence if trim == 0 else sequence[:-trim]


def build_records(
    target_regions: dict[str, Assembly],
    b_regions: dict[str, Assembly],
    extras_by_genotype: dict[str, list[GenomeExtra]],
    rng: random.Random,
    flank_length: int,
    flank_jitter: int,
) -> dict[str, DatasetRecord]:
    master_length = flank_length + flank_jitter
    shared_left = random_dna(rng, master_length)
    shared_right = random_dna(rng, master_length)
    records: dict[str, DatasetRecord] = {}

    for genotype in GENOTYPES:
        left = trim_left(shared_left, rng, flank_jitter)
        right = trim_right(shared_right, rng, flank_jitter)
        target_region = target_regions[genotype]
        b_region = b_regions[genotype]

        target_segments = [
            Segment("left_flank", "shared_left_flank", left),
            *target_region.segments,
            Segment("right_flank", "shared_right_flank", right),
        ]
        b_segments = [
            Segment("left_flank", "shared_left_flank", mutate_homoeologue(left)),
            *b_region.segments,
            Segment("right_flank", "shared_right_flank", mutate_homoeologue(right)),
        ]

        records[genotype] = DatasetRecord(
            genotype=genotype,
            target_region=target_region,
            homoeologue_region=b_region,
            target_genome=Assembly(
                "".join(segment.sequence for segment in target_segments),
                target_segments,
            ),
            homoeologue_genome=Assembly(
                "".join(segment.sequence for segment in b_segments),
                b_segments,
            ),
            region_start_1based=len(left) + 1,
            genome_extras=tuple(extras_by_genotype[genotype]),
        )

    return records


def reset_directory(path: Path) -> None:
    """Recreate a generated fixture subdirectory without touching results/."""
    if path.exists():
        shutil.rmtree(path)
    path.mkdir(parents=True, exist_ok=True)


def write_dataset(output_dir: Path, records: dict[str, DatasetRecord]) -> None:
    regions_dir = output_dir / "regions"
    genomes_dir = output_dir / "genomes"
    reset_directory(regions_dir)
    reset_directory(genomes_dir)

    for genotype in GENOTYPES:
        record = records[genotype]
        write_fasta(
            regions_dir / f"{genotype}.fasta",
            [(target_record_name(genotype), record.target_region.sequence)],
        )

        whole_genome_records = [
            (target_record_name(genotype), record.target_genome.sequence),
            (homoeologue_record_name(genotype), record.homoeologue_genome.sequence),
        ]
        whole_genome_records.extend(
            (
                extra_record_name(genotype, extra, index),
                extra.sequence,
            )
            for index, extra in enumerate(record.genome_extras, start=1)
        )
        write_fasta(
            genomes_dir / f"{genotype}.fasta",
            whole_genome_records,
        )

    with (output_dir / "genotypes.tsv").open("w", encoding="utf-8") as handle:
        handle.write(
            "genotype\tgroup\tregion_fasta\tgenome_fasta\tsource_seq\tregion_start\n"
        )
        for genotype in GENOTYPES:
            record = records[genotype]
            group = GROUP_BY_GENOTYPE.get(genotype, "")
            handle.write(
                f"{genotype}\t{group}\tregions/{genotype}.fasta\t"
                f"genomes/{genotype}.fasta\t{target_record_name(genotype)}\t"
                f"{record.region_start_1based}\n"
            )

    with (output_dir / "chromosomes.tsv").open("w", encoding="utf-8") as handle:
        handle.write("genotype\tseq_id\thomoeologous_group\tsubgenome\n")
        for genotype in GENOTYPES:
            record = records[genotype]
            handle.write(
                f"{genotype}\t{target_record_name(genotype)}\t"
                f"{HOMOEOLOGOUS_GROUP}\t{TARGET_SUBGENOME}\n"
            )
            handle.write(
                f"{genotype}\t{homoeologue_record_name(genotype)}\t"
                f"{HOMOEOLOGOUS_GROUP}\t{HOMOEOLOGUE_SUBGENOME}\n"
            )
            for index, extra in enumerate(record.genome_extras, start=1):
                handle.write(
                    f"{genotype}\t{extra_record_name(genotype, extra, index)}\t"
                    f"{extra.homoeologous_group}\t{extra.subgenome}\n"
                )


def copy_annotations(source_dir: Path, output_dir: Path) -> None:
    source_table = source_dir / "annotations.tsv"
    source_gff_dir = source_dir / "gffs"
    output_gff_dir = output_dir / "annotations"

    if not source_table.is_file():
        raise ValueError(f"Missing source annotations table: {source_table}")
    if not source_gff_dir.is_dir():
        raise ValueError(f"Missing source GFF directory: {source_gff_dir}")

    reset_directory(output_gff_dir)

    with source_table.open("r", encoding="utf-8", newline="") as source_handle:
        reader = csv.DictReader(source_handle, delimiter="\t")
        expected = {"genotype", "track", "gff"}
        if reader.fieldnames is None or set(reader.fieldnames) != expected:
            raise ValueError(
                f"{source_table}: expected columns genotype, track, gff"
            )
        rows = list(reader)

    output_table = output_dir / "annotations.tsv"
    with output_table.open("w", encoding="utf-8", newline="") as output_handle:
        writer = csv.DictWriter(
            output_handle,
            fieldnames=["genotype", "track", "gff"],
            delimiter="\t",
            lineterminator="\n",
        )
        writer.writeheader()

        for row in rows:
            configured_gff = Path(row["gff"])
            if configured_gff.is_absolute():
                raise ValueError(
                    f"{source_table}: source GFF paths must be relative to "
                    f"{source_dir}: {configured_gff}"
                )

            source_gff = (source_dir / configured_gff).resolve()
            try:
                source_gff.relative_to(source_dir.resolve())
            except ValueError as error:
                raise ValueError(
                    f"{source_table}: GFF path escapes source directory: "
                    f"{configured_gff}"
                ) from error

            if not source_gff.is_file():
                raise ValueError(
                    f"GFF referenced by {source_table} not found: {source_gff}"
                )

            gff_name = source_gff.name
            destination = output_gff_dir / gff_name
            shutil.copy2(source_gff, destination)

            writer.writerow(
                {
                    "genotype": row["genotype"],
                    "track": row["track"],
                    "gff": f"annotations/{gff_name}",
                }
            )


def copy_repeat_library(source_dir: Path, output_dir: Path) -> None:
    source_library = source_dir / "resources" / "mini_TE_lib.fasta"
    output_resources = output_dir / "resources"

    if not source_library.is_file():
        raise ValueError(
            "Missing smoke-test repeat library: "
            f"{source_library}\n"
            "Place the versioned mini_TE_lib.fasta under "
            "dev/smoke_test_builder/source/resources/."
        )

    reset_directory(output_resources)
    shutil.copy2(source_library, output_resources / "mini_TE_lib.fasta")


def write_config(output_dir: Path) -> None:
    config_text = """project:
  name: "Test dataset"

inputs:
  genotypes: genotypes.tsv
  annotations: annotations.tsv
  chromosomes: chromosomes.tsv

snps:
  min_block_length: 450
  repeat_masking:
    library: resources/mini_TE_lib.fasta

kasp:
  polymarker_genomes: 2
  mfeprimer:
    specificity:
      min_tm: 50
    dimer:
      max_dg: -3.5

viewer:
  dotplot_reference: null

advanced:
  sibeliaz:
    extra_options: []
  batching:
    blocks_per_chunk: 2
  alignment:
    mafft_options: []
  mfeprimer:
    kmer_size: 9
    specificity_extra_options: []
    dimer_extra_options: []
    hairpin_extra_options: []
"""
    (output_dir / "config.yaml").write_text(config_text, encoding="utf-8")


def main() -> None:
    args = parse_args()

    if args.spacer_length < 0:
        raise ValueError("--spacer-length must be >= 0")
    if args.flank_length < 0:
        raise ValueError("--flank-length must be >= 0")
    if args.flank_jitter < 0:
        raise ValueError("--flank-jitter must be >= 0")

    source_dir = args.source_dir.expanduser().resolve()
    output_dir = args.output_dir.expanduser().resolve()

    blocks_dir = source_dir / "blocks"
    genome_extras_dir = source_dir / "genome_extras"

    rng = random.Random(args.seed)
    blocks = load_blocks(blocks_dir)
    extras_by_genotype = load_genome_extras(genome_extras_dir)
    target_regions, b_regions = assemble_regions(
        blocks,
        rng,
        args.spacer_length,
    )
    records = build_records(
        target_regions,
        b_regions,
        extras_by_genotype,
        rng,
        args.flank_length,
        args.flank_jitter,
    )

    output_dir.mkdir(parents=True, exist_ok=True)

    write_dataset(output_dir, records)
    copy_annotations(source_dir, output_dir)
    copy_repeat_library(source_dir, output_dir)
    write_config(output_dir)

    print(f"Smoke-test fixture written to: {output_dir}")
    print("Runtime inputs generated/copied:")
    print("  config.yaml")
    print("  genotypes.tsv")
    print("  chromosomes.tsv")
    print("  annotations.tsv")
    print("  regions/")
    print("  genomes/")
    print("  annotations/")
    print("  resources/")
    print("Existing results/ was left untouched.")


if __name__ == "__main__":
    main()
